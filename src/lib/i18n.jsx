// ── Store de limbă (fără provider — modul independent) ───────────────────────
function initialLang() {
  try {
    const v = localStorage.getItem('forma_lang')
    return v === 'en' ? 'en' : 'ro'
  } catch (_) { return 'ro' }
}

let _lang = initialLang()
const _listeners = new Set()

export function getLang() { return _lang }

export function setLang(l) {
  const v = l === 'en' ? 'en' : 'ro'
  if (v === _lang) return
  _lang = v
  try { localStorage.setItem('forma_lang', v) } catch (_) {}
  _listeners.forEach(fn => { try { fn(v) } catch (_) {} })
}

// Traducere pură (folosește limba curentă din store)
export function translate(ro) {
  if (_lang === 'ro' || ro == null) return ro
  return EN[ro] !== undefined ? EN[ro] : ro
}

// ── Hook React — re-randează componenta la schimbarea limbii ─────────────────
export function useI18n() {
  const [lang, setLangState] = useState(_lang)
  useEffect(() => {
    const fn = (l) => setLangState(l)
    _listeners.add(fn)
    // sincronizează dacă s-a schimbat între render și montare
    if (_lang !== lang) setLangState(_lang)
    return () => { _listeners.delete(fn) }
  }, []) // eslint-disable-line react-hooks/exhaustive-deps

  const t = (ro) => (lang === 'ro' || ro == null ? ro : (EN[ro] !== undefined ? EN[ro] : ro))
  return { lang, setLang, t }
}
